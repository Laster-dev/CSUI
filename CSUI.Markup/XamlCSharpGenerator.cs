using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;
using System.Windows;
using System.Windows.Media;
using System.Xml.Linq;

namespace CSUI.Markup
{
    /// <summary>
    /// Compile-time and build-time XAML-to-C# code generator.
    /// Compiles XAML documents with x:Class (and optional x:DataType) into static, zero-reflection C# partial classes
    /// with strongly-typed named fields, InitializeComponent(), and Binding.Create&lt;TData, TProp&gt; delegates.
    /// </summary>
    public static class XamlCSharpGenerator
    {
        public static string GeneratePartialClass(string xamlContent, string fallbackNamespace = "CSUI.Generated")
        {
            ArgumentNullException.ThrowIfNull(xamlContent);
            XDocument doc = XDocument.Parse(xamlContent);
            XElement root = doc.Root ?? throw new InvalidOperationException("XAML document has no root element.");

            string xClass = GetAttributeByLocalName(root, "Class");
            string xDataType = GetAttributeByLocalName(root, "DataType");

            string ns = fallbackNamespace;
            string className = "GeneratedXamlView";
            if (!string.IsNullOrEmpty(xClass))
            {
                int lastDot = xClass.LastIndexOf('.');
                if (lastDot > 0)
                {
                    ns = xClass.Substring(0, lastDot);
                    className = xClass.Substring(lastDot + 1);
                }
                else
                {
                    className = xClass;
                }
            }

            string rootTypeName = root.Name.LocalName;
            var namedFields = new List<(string typeName, string fieldName)>();
            CollectNamedElements(root, isRoot: true, namedFields);

            var sb = new StringBuilder(4096);
            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("// Generated by CSUI.Markup.XamlCSharpGenerator (Zero-Reflection NativeAOT)");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine("#nullable disable");
            sb.AppendLine("using System;");
            sb.AppendLine("using System.Windows;");
            sb.AppendLine("using System.Windows.Controls;");
            sb.AppendLine("using System.Windows.Data;");
            sb.AppendLine("using System.Windows.Input;");
            sb.AppendLine("using System.Windows.Media;");
            sb.AppendLine("using System.Windows.Media.Media3D;");
            sb.AppendLine("using CSUI.Markup;");
            sb.AppendLine();
            sb.AppendLine($"namespace {ns}");
            sb.AppendLine("{");
            sb.AppendLine($"    partial class {className} : {rootTypeName}");
            sb.AppendLine("    {");
            sb.AppendLine("        private bool _contentLoaded;");

            for (int i = 0; i < namedFields.Count; i++)
            {
                sb.AppendLine($"        internal {namedFields[i].typeName} {namedFields[i].fieldName};");
            }

            sb.AppendLine();
            sb.AppendLine("        public void InitializeComponent()");
            sb.AppendLine("        {");
            sb.AppendLine("            if (_contentLoaded) return;");
            sb.AppendLine("            _contentLoaded = true;");
            sb.AppendLine();

            int varCounter = 0;
            EmitElementInitialization(sb, root, "this", rootTypeName, xDataType, ref varCounter, "            ");

            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        private static void CollectNamedElements(XElement el, bool isRoot, List<(string typeName, string fieldName)> list)
        {
            if (!isRoot && !el.Name.LocalName.Contains('.'))
            {
                string name = GetAttributeByLocalName(el, "Name");
                if (!string.IsNullOrEmpty(name))
                {
                    list.Add((el.Name.LocalName, name));
                }
            }

            foreach (XElement child in el.Elements())
            {
                if (child.Name.LocalName == "ControlTemplate" || child.Name.LocalName == "Style")
                {
                    continue;
                }
                CollectNamedElements(child, isRoot: false, list);
            }
        }

        private static void EmitElementInitialization(
            StringBuilder sb,
            XElement el,
            string targetVar,
            string typeName,
            string xDataType,
            ref int varCounter,
            string indent)
        {
            Type clrType = XamlMarkup.ResolveTypeName(typeName);

            foreach (XAttribute attr in el.Attributes())
            {
                if (attr.IsNamespaceDeclaration) continue;
                string attrName = attr.Name.LocalName;
                string rawVal = attr.Value;

                if (attrName is "Class" or "DataType" or "Key")
                {
                    continue;
                }
                if (attrName == "Name")
                {
                    sb.AppendLine($"{indent}{targetVar}.Name = \"{EscapeString(rawVal)}\";");
                    if (targetVar != "this")
                    {
                        sb.AppendLine($"{indent}this.{rawVal} = {targetVar};");
                    }
                    continue;
                }

                EmitAttributeStatement(sb, targetVar, typeName, clrType, attrName, rawVal, xDataType, indent);
            }

            foreach (XElement childEl in el.Elements())
            {
                string childLocal = childEl.Name.LocalName;
                int dotIdx = childLocal.IndexOf('.');
                if (dotIdx > 0)
                {
                    string propPart = childLocal.Substring(dotIdx + 1);
                    if (propPart == "Resources")
                    {
                        foreach (XElement resItem in childEl.Elements())
                        {
                            EmitResourceEntry(sb, targetVar, resItem, xDataType, ref varCounter, indent);
                        }
                    }
                    else
                    {
                        foreach (XElement valEl in childEl.Elements())
                        {
                            varCounter++;
                            string childVar = $"_el{varCounter}";
                            string valTypeName = valEl.Name.LocalName;
                            sb.AppendLine($"{indent}var {childVar} = new {valTypeName}();");
                            EmitElementInitialization(sb, valEl, childVar, valTypeName, xDataType, ref varCounter, indent);
                            sb.AppendLine($"{indent}{targetVar}.{propPart} = {childVar};");
                        }
                    }
                }
                else
                {
                    varCounter++;
                    string childVar = $"_el{varCounter}";
                    sb.AppendLine($"{indent}var {childVar} = new {childLocal}();");
                    EmitElementInitialization(sb, childEl, childVar, childLocal, xDataType, ref varCounter, indent);
                    EmitAddChildStatement(sb, targetVar, clrType, childVar, indent);
                }
            }
        }

        private static void EmitResourceEntry(
            StringBuilder sb,
            string ownerVar,
            XElement resEl,
            string xDataType,
            ref int varCounter,
            string indent)
        {
            if (resEl.Name.LocalName == "ResourceDictionary")
            {
                foreach (XElement inner in resEl.Elements())
                {
                    EmitResourceEntry(sb, ownerVar, inner, xDataType, ref varCounter, indent);
                }
                return;
            }

            string key = GetAttributeByLocalName(resEl, "Key");
            varCounter++;
            string resVar = $"_res{varCounter}";
            string resType = resEl.Name.LocalName;
            sb.AppendLine($"{indent}var {resVar} = new {resType}();");
            EmitElementInitialization(sb, resEl, resVar, resType, xDataType, ref varCounter, indent);
            if (!string.IsNullOrEmpty(key))
            {
                sb.AppendLine($"{indent}{ownerVar}.Resources[\"{EscapeString(key)}\"] = {resVar};");
            }
        }

        private static void EmitAttributeStatement(
            StringBuilder sb,
            string targetVar,
            string typeName,
            Type clrType,
            string attrName,
            string rawVal,
            string xDataType,
            string indent)
        {
            string trimmed = rawVal.Trim();
            int dotIdx = attrName.IndexOf('.');
            string dpOwnerExpr = dotIdx > 0 ? attrName.Substring(0, dotIdx) : typeName;
            string dpPropName = dotIdx > 0 ? attrName.Substring(dotIdx + 1) : attrName;

            DependencyProperty dp = dotIdx > 0
                ? XamlMarkup.ResolveDependencyProperty(dpOwnerExpr, dpPropName)
                : (clrType != null ? XamlMarkup.ResolveDependencyPropertyForInstance(clrType, dpPropName) : null);

            if (trimmed.StartsWith('{') && trimmed.EndsWith('}'))
            {
                string inner = trimmed.Substring(1, trimmed.Length - 2).Trim();
                if (inner.StartsWith("DynamicResource ", StringComparison.Ordinal))
                {
                    string key = inner.Substring("DynamicResource ".Length).Trim();
                    sb.AppendLine($"{indent}{targetVar}.SetResourceReference({dpOwnerExpr}.{dpPropName}Property, \"{EscapeString(key)}\");");
                    return;
                }
                if (inner.StartsWith("StaticResource ", StringComparison.Ordinal))
                {
                    string key = inner.Substring("StaticResource ".Length).Trim();
                    sb.AppendLine($"{indent}{targetVar}.SetValue({dpOwnerExpr}.{dpPropName}Property, {targetVar}.TryFindResource(\"{EscapeString(key)}\"));");
                    return;
                }
                if ((inner.StartsWith("Binding", StringComparison.Ordinal) || inner.StartsWith("x:Bind", StringComparison.Ordinal)) &&
                    !string.IsNullOrEmpty(xDataType))
                {
                    string path = XamlMarkup.ExtractBindingPath(inner);
                    bool twoWay = inner.Contains("Mode=TwoWay", StringComparison.OrdinalIgnoreCase);
                    string propType = dp != null ? GetFriendlyCSharpTypeName(dp.PropertyType) : "object";
                    if (twoWay)
                    {
                        sb.AppendLine($"{indent}BindingOperations.SetBinding({targetVar}, {dpOwnerExpr}.{dpPropName}Property, Binding.Create<{xDataType}, {propType}>(static m => m.{path}, static (m, v) => m.{path} = v, nameof({xDataType}.{path})));");
                    }
                    else
                    {
                        sb.AppendLine($"{indent}BindingOperations.SetBinding({targetVar}, {dpOwnerExpr}.{dpPropName}Property, Binding.Create<{xDataType}, {propType}>(static m => m.{path}, null, nameof({xDataType}.{path})));");
                    }
                    return;
                }
            }

            if (dotIdx > 0)
            {
                string literal = FormatCSharpLiteral(rawVal, dp?.PropertyType ?? typeof(double));
                sb.AppendLine($"{indent}{targetVar}.SetValue({dpOwnerExpr}.{dpPropName}Property, {literal});");
                return;
            }

            string valueExpr = FormatCSharpLiteral(rawVal, dp?.PropertyType ?? typeof(string));
            sb.AppendLine($"{indent}{targetVar}.{attrName} = {valueExpr};");
        }

        private static void EmitAddChildStatement(StringBuilder sb, string parentVar, Type parentClrType, string childVar, string indent)
        {
            if (parentClrType != null)
            {
                if (typeof(System.Windows.Controls.Panel).IsAssignableFrom(parentClrType) ||
                    typeof(System.Windows.Controls.Viewport3D).IsAssignableFrom(parentClrType) ||
                    typeof(System.Windows.Media.Media3D.Model3DGroup).IsAssignableFrom(parentClrType) ||
                    typeof(System.Windows.Media.Media3D.MaterialGroup).IsAssignableFrom(parentClrType) ||
                    typeof(System.Windows.Media.Media3D.Transform3DGroup).IsAssignableFrom(parentClrType) ||
                    typeof(System.Windows.Media.Media3D.ContainerUIElement3D).IsAssignableFrom(parentClrType))
                {
                    sb.AppendLine($"{indent}{parentVar}.Children.Add({childVar});");
                    return;
                }
                if (typeof(System.Windows.Controls.Decorator).IsAssignableFrom(parentClrType))
                {
                    sb.AppendLine($"{indent}{parentVar}.Child = {childVar};");
                    return;
                }
                if (typeof(System.Windows.Controls.ContentControl).IsAssignableFrom(parentClrType) ||
                    typeof(System.Windows.Media.Media3D.ModelVisual3D).IsAssignableFrom(parentClrType))
                {
                    sb.AppendLine($"{indent}{parentVar}.Content = {childVar};");
                    return;
                }
            }
            sb.AppendLine($"{indent}((System.Windows.Markup.IAddChild){parentVar}).AddChild({childVar});");
        }

        private static string FormatCSharpLiteral(string raw, Type targetType)
        {
            if (targetType == typeof(double))
            {
                if (string.Equals(raw, "Auto", StringComparison.OrdinalIgnoreCase) ||
                    string.Equals(raw, "NaN", StringComparison.OrdinalIgnoreCase))
                {
                    return "double.NaN";
                }
                double d = double.Parse(raw, CultureInfo.InvariantCulture);
                return d.ToString("R", CultureInfo.InvariantCulture) + (d == Math.Floor(d) ? ".0" : "");
            }
            if (targetType == typeof(int))
            {
                return int.Parse(raw, CultureInfo.InvariantCulture).ToString(CultureInfo.InvariantCulture);
            }
            if (targetType == typeof(bool))
            {
                return bool.Parse(raw) ? "true" : "false";
            }
            if (targetType == typeof(Color))
            {
                Color c = XamlMarkup.ParseColor(raw);
                return $"Color.FromArgb({c.A}, {c.R}, {c.G}, {c.B})";
            }
            if (typeof(System.Windows.Media.Brush).IsAssignableFrom(targetType))
            {
                Color c = XamlMarkup.ParseColor(raw);
                return $"new SolidColorBrush(Color.FromArgb({c.A}, {c.R}, {c.G}, {c.B}))";
            }
            if (targetType == typeof(Thickness))
            {
                Thickness t = XamlMarkup.ParseThickness(raw);
                return $"new Thickness({t.Left.ToString(CultureInfo.InvariantCulture)}, {t.Top.ToString(CultureInfo.InvariantCulture)}, {t.Right.ToString(CultureInfo.InvariantCulture)}, {t.Bottom.ToString(CultureInfo.InvariantCulture)})";
            }
            if (targetType.IsEnum)
            {
                return $"{targetType.Name}.{raw}";
            }
            return $"\"{EscapeString(raw)}\"";
        }

        private static string GetFriendlyCSharpTypeName(Type type)
        {
            if (type == typeof(double)) return "double";
            if (type == typeof(int)) return "int";
            if (type == typeof(bool)) return "bool";
            if (type == typeof(string)) return "string";
            return type.FullName ?? type.Name;
        }

        private static string GetAttributeByLocalName(XElement el, string localName)
        {
            foreach (XAttribute attr in el.Attributes())
            {
                if (!attr.IsNamespaceDeclaration && attr.Name.LocalName == localName)
                {
                    return attr.Value;
                }
            }
            return null;
        }

        private static string EscapeString(string s)
        {
            return s?.Replace("\\", "\\\\").Replace("\"", "\\\"") ?? string.Empty;
        }
    }
}
